type SectionProps = {
  id: string;
  scene: SceneKind;
  seed: number;
  eyebrow: string;
  title: ReactNode;
  children: ReactNode;
  actions?: ReactNode;
  hero?: boolean;
};

function Section({ id, scene, seed, eyebrow, title, children, actions, hero }: SectionProps) {
  const Heading = hero ? "h1" : "h2";
  return (
    <section id={id} className={`lp-section${hero ? " lp-hero" : ""}`} aria-labelledby={`${id}-title`}>
      <Backdrop scene={scene} seed={seed} />
      <div className="lp-shade" aria-hidden />
      <div className="lp-content">
        <p className="lp-eyebrow">{eyebrow}</p>
        <Heading id={`${id}-title`} className="lp-title">
          {title}
        </Heading>
        <div className="lp-body">{children}</div>
        {actions && <div className="lp-actions">{actions}</div>}
      </div>
      <p className="lp-caption">Animated illustration — not satellite imagery or real data</p>
    </section>
  );
}

