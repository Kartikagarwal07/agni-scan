import { readFileSync } from "node:fs";

const riskGrid: unknown = JSON.parse(
  readFileSync(new URL("../data-pipeline/demo/risk_grid.geojson", import.meta.url), "utf8"),
);

export type RiskLevel = "low" | "medium" | "high" | "unknown";
export type VerificationStatus =
  | "unverified"
  | "scheduled"
  | "verified_fire"
  | "verified_no_fire";

export type RiskCellProperties = {
  cell_id: string;
  district: string;
  risk_score: number | null;
  risk_level: RiskLevel;
  observed_fire_count: number;
  evidence_completeness: number;
  verification_status: VerificationStatus;
  analysis_date: string;
};

export type RiskCell = {
  type: "Feature";
  id: string;
  geometry: { type: "Polygon"; coordinates: number[][][] };
  properties: RiskCellProperties;
};

export type RiskGrid = {
  type: "FeatureCollection";
  metadata: Record<string, unknown>;
  features: readonly RiskCell[];
};

export type InspectionResult =
  | "fire_evidence_found"
  | "no_fire_evidence_found"
  | "inconclusive";

export type Inspection = {
  id: string;
  cell_id: string;
  result: InspectionResult;
  notes: string;
  created_at: string;
};

export class RequestValidationError extends Error {}

function isClosedRing(ring: number[][]) {
  return ring.length >= 4 && ring[0].length === 2 && ring.at(-1)?.length === 2 && ring[0][0] === ring.at(-1)?.[0] && ring[0][1] === ring.at(-1)?.[1];
}

function assertRiskGrid(value: unknown): asserts value is RiskGrid {
  if (typeof value !== "object" || value === null) throw new Error("Risk grid must be an object.");
  const grid = value as Partial<RiskGrid>;
  if (grid.type !== "FeatureCollection" || !Array.isArray(grid.features) || typeof grid.metadata !== "object" || grid.metadata === null) {
    throw new Error("Risk grid must be a GeoJSON FeatureCollection with metadata.");
  }

  for (const feature of grid.features) {
    const properties = feature?.properties;
    const ring = feature?.geometry?.coordinates?.[0];
    if (
      feature?.type !== "Feature" ||
      feature.geometry?.type !== "Polygon" ||
      !Array.isArray(ring) ||
      !isClosedRing(ring) ||
      feature.id !== properties?.cell_id ||
      typeof properties?.cell_id !== "string" ||
      typeof properties.district !== "string" ||
      (properties.risk_score !== null && (typeof properties.risk_score !== "number" || properties.risk_score < 0 || properties.risk_score > 100)) ||
      !["low", "medium", "high", "unknown"].includes(properties.risk_level) ||
      !Number.isInteger(properties.observed_fire_count) ||
      properties.observed_fire_count < 0 ||
      typeof properties.evidence_completeness !== "number" ||
      properties.evidence_completeness < 0 ||
      properties.evidence_completeness > 1 ||
      !["unverified", "scheduled", "verified_fire", "verified_no_fire"].includes(properties.verification_status) ||
      !/^\d{4}-\d{2}-\d{2}$/.test(properties.analysis_date)
    ) {
      throw new Error("Risk grid does not conform to the shared data contract.");
    }
  }
}

assertRiskGrid(riskGrid);

// Generated by data-pipeline/demo. This synthetic collection is deliberately
// served unchanged so clients receive its provenance and safety disclaimer.
export const RISK_GRID: RiskGrid = riskGrid;
export const GRID_METADATA = RISK_GRID.metadata;

export function parsePagination(searchParams: URLSearchParams) {
  const limit = parseInteger(searchParams.get("limit"), 20, 1, 100, "limit");
  const offset = parseInteger(searchParams.get("offset"), 0, 0, Number.MAX_SAFE_INTEGER, "offset");
  return { limit, offset };
}

function parseInteger(value: string | null, fallback: number, min: number, max: number, name: string) {
  if (value === null) return fallback;
  if (!/^\d+$/.test(value)) throw new RequestValidationError(`${name} must be an integer.`);
  const number = Number(value);
  if (number < min || number > max) throw new RequestValidationError(`${name} must be between ${min} and ${max}.`);
  return number;
}

export function requireDate(value: string | null) {
  if (value !== null && !/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    throw new RequestValidationError("date must use YYYY-MM-DD format.");
  }
  return value;
}

export function requireRiskLevel(value: string | null): RiskLevel | null {
  if (value === null) return null;
  if (!(["low", "medium", "high", "unknown"] as const).includes(value as RiskLevel)) {
    throw new RequestValidationError("risk_level must be low, medium, high, or unknown.");
  }
  return value as RiskLevel;
}

export function gridFor(searchParams: URLSearchParams) {
  const district = searchParams.get("district");
  const date = requireDate(searchParams.get("date"));
  const riskLevel = requireRiskLevel(searchParams.get("risk_level"));
  return RISK_GRID.features.filter(({ properties }) =>
    (district === null || properties.district === district) &&
    (date === null || properties.analysis_date === date) &&
    (riskLevel === null || properties.risk_level === riskLevel),
  );
}

export function validationError(message = "Invalid request parameters") {
  return { error: { code: "VALIDATION_ERROR", message } };
}

export function notFoundError(message = "Resource not found") {
  return { error: { code: "NOT_FOUND", message } };
}

export function parseInspection(value: unknown): Pick<Inspection, "cell_id" | "result" | "notes"> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new RequestValidationError("Request body must be a JSON object.");
  }
  const body = value as Record<string, unknown>;
  const { cell_id, result, notes } = body;
  if (typeof cell_id !== "string" || !RISK_GRID.features.some((cell) => cell.properties.cell_id === cell_id)) {
    throw new RequestValidationError("cell_id must identify an existing grid cell.");
  }
  if (!(["fire_evidence_found", "no_fire_evidence_found", "inconclusive"] as const).includes(result as InspectionResult)) {
    throw new RequestValidationError("result is not an allowed inspection result.");
  }
  if (typeof notes !== "string" || notes.trim().length === 0 || notes.length > 1000) {
    throw new RequestValidationError("notes must be a non-empty string of at most 1000 characters.");
  }
  return { cell_id, result: result as InspectionResult, notes: notes.trim() };
}
